/**
 * 范围守卫：这个软件**只做小说写作**，把与写作无关的、试图改造软件身份的请求挡在模型之前。
 *
 * ## 为什么要单独一个模块
 *
 * 1. 它是**安全边界**（哪怕只是"不让用户拿我的 key 去跑别的活"），
 *    逻辑必须能单测 —— 混进 main.js 就只能靠手点，而手点永远点不全。
 * 2. 规则表本身会一直改（加一条词、去一条误报）。规则和状态机分开写，
 *    改规则不用碰发送链路。
 *
 * ## 四级处置（2026-10-16 羽毛菌定的规矩）
 *
 *   allow   放行
 *   warn    **不回复**，记一次警告；累计 2 次 → 锁
 *   lock    **直接锁**：关掉模型连接，发不出任何文字
 *   silent  不回复、也不记警告（问模型名、把工具当人叫爸妈这类）
 *
 * ⚠⚠ `warn` 里有一类带 `agreement: true`（涉及法律 / 道德伦理的具体做法）。
 *   它**第一次不直接锁**（2026-10-16 羽毛菌改定）：拦下之后弹《用户协议》，
 *   用户勾选同意就放行那一次；不勾选则不发送；第二次再犯才关连接。
 *   越狱 / 身份改写 / 索取内部设定那一组仍然是直接锁 ——
 *   那是"改造软件本身"，跟"内容不合规"不是一回事。
 *
 * ⚠⚠ 误报是这个功能最大的风险，而且**代价不对称**：
 *   放过去一条越狱 = 软件被当成通用助手用一次；
 *   拦掉一句正常的写作请求 = 用户以为软件坏了。
 *   所以规则一律**窄**：只打高信号、几乎不可能出现在正常写作里的说法。
 *
 * ⚠⚠ **小说里可以写犯罪**。禁止的是"教我怎么做"的**操作型**提问，
 *   不是情节本身 —— 「夜枫下毒那一段怎么写才不突兀」必须放行。
 *   所以涉及违法内容的规则都要求**同时**出现操作形状词
 *   （教我 / 怎么制作 / 具体步骤…），单出现"毒药""杀人"一律不拦。
 *   （判据 `test-scope-guard.js` 里有一组"必须放行"的用例专门守这条。）
 */

