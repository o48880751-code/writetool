/** 只读导出，判据要用它做覆盖检查 */
module.exports = { RULES };

/**
 * 判定一条用户输入。
 *
 * @param {string} text
 * @returns {{level:'allow'|'warn'|'lock'|'silent', id:string|null, notice:string, agreement:boolean}}
 */
function classify(text) {
  const t = String(text || '');
  if (!t.trim()) return { level: 'allow', id: null, notice: '', agreement: false };
  for (const r of RULES) {
    /**
     * ⚠ `exempt` 命中就**跳过这条规则**（2026-10-18 加）。
     *
     * 现在只有 `roleplay` 用它：用户说了「写 / 章节 / 对白」就是在写小说，
     * 句子里出现"儿子/爸爸"是剧情台词，不是在对 AI 说话。
     * 没有这道门，「帮我写一段父子对话：儿子，我想多听你叫几声」
     * 会被当成认亲拦下来 —— 那是把正常创作挡在门外。
     */
    if (r.exempt && r.exempt.test(t)) continue;
    // ⚠ 规则里**不要写 `g` flag**：`test()` 会记住 lastIndex，
    //   同一份规则连着测两条会跳着匹配（假阴性）。
    if (r.re.test(t)) {
      return {
        level: r.level, id: r.id,
        notice: r.notice || '',
        // ⚠ 只给"需要用户同意"的那一类打标；其余一律 false，
        //   界面才不会对普通警告也弹协议。
        agreement: r.agreement === true,
      };
    }
  }
  return { level: 'allow', id: null, notice: '', agreement: false };
}

/**
 * 守卫状态机：警告计数 + 锁。
 *
 * ⚠ 状态**落盘**（写进 config）：用户重启软件也还是锁着的 ——
 *   羽毛菌要的是"关闭模型连接功能"，重启就复活等于没关。
 * ⚠ 但留一条明路：`unlock()`（设置页有按钮）。这是用户自己的软件，
 *   锁的目的是"别拿它干别的"，不是把用户关在门外。
 */
const MAX_STRIKES = 2;

class ScopeGuard {
  /**
   * @param {object} opt
   * @param {() => {strikes?:number, locked?:boolean}} [opt.read]  读持久化状态
   * @param {(patch:object) => void} [opt.write]                   写持久化状态
   */
  constructor({ read, write } = {}) {
    const s = (read && read()) || {};
    this.strikes = Number(s.strikes) || 0;
    this.locked = s.locked === true;
    this._write = write || (() => {});
  }

  get isLocked() { return this.locked === true; }

  _persist() {
    try { this._write({ strikes: this.strikes, locked: this.locked }); } catch (_) { /* 存不下不影响本次拦截 */ }
  }

  /**
   * 过一条用户输入。
   *
   * @returns {{level, id, locked:boolean, strikes:number, text:string}}
   *   level: allow（放行）/ warn（第一次警告，不回复）/ locked（已锁或本轮直接锁）
   *          / silent（静默不回复）
   */
  check(text) {
    // 已经锁了：任何输入都发不出去
    if (this.locked) {
      return {
        level: 'locked', id: 'locked', locked: true, strikes: this.strikes, agreement: false,
        text: '模型连接已关闭（之前有与小说创作无关的请求被拦下）。'
          + '要恢复，去「设置 → 参数」点「重新启用模型连接」。',
      };
    }
    const v = classify(text);
    if (v.level === 'allow') {
      return {
        level: 'allow', id: null, locked: false,
        strikes: this.strikes, agreement: false, text: '',
      };
    }
    if (v.level === 'silent') {
      /**
       * ⚠ 「不予回复」不等于"界面上什么都不发生" —— 什么都不发生会被当成软件坏了。
       *   所以给一句**中性的说明**（不是模型说的话，是软件说的话），
       *   内容不含任何答案（尤其不能出现模型名/身份）。
       */
      return {
        level: 'silent', id: v.id, locked: false, strikes: this.strikes, agreement: false,
        text: v.notice || '（这类问题不回答。这个工具是干什么的、怎么用，可以问。）',
      };
    }
    if (v.level === 'lock') {
      this.locked = true;
      this._persist();
      /**
       * ⚠ 文案里**必须带上"怎么恢复"**：直接锁是兜底手段，
       *   用户看到的如果只有"不行"，他会以为软件坏了。
       *   （判据 test-scope-e2e.js 会检查"原因 + 恢复路径"两件事。）
       */
      return {
        level: 'locked', id: v.id, locked: true, strikes: this.strikes, agreement: false,
        text: `${v.notice}模型连接已关闭 —— 在「设置 → 参数」里可以重新启用。`,
      };
    }
    // warn：记一次
    this.strikes += 1;
    if (this.strikes >= MAX_STRIKES) {
      this.locked = true;
      this._persist();
      return {
        level: 'locked', id: v.id, locked: true, strikes: this.strikes,
        // ⚠ 第二次不给 agreement：这时候已经没有"同意就能继续"这条路了
        agreement: false,
        text: `${v.notice}这已经是第 ${this.strikes} 次，模型连接已关闭 ——`
          + '要恢复，去「设置 → 参数」点「重新启用模型连接」。',
      };
    }
    this._persist();
    /**
     * ⚠ 别再重复一遍 notice：offtopic 的 notice 本身就是「这个工具只用于小说创作。」，
     *   拼上模板句式会变成"…只用于小说创作。这个工具只用于小说创作 ——…"（实测这么出来过）。
     */
    return {
      level: 'warn', id: v.id, locked: false, strikes: this.strikes,
      agreement: v.agreement === true,
      // ⚠ 需要用户同意的那一类，文案里必须点名《用户协议》——
      //   界面上会弹窗让人勾选，这句话是弹窗的引子。
      text: v.agreement
        ? `${v.notice}请阅读《用户协议》并勾选同意后再继续；再问一次就会关闭模型连接。`
        : `${v.notice}再问一次就会关闭模型连接。`,
    };
  }

  /** 用户自己解锁（设置页）：清空计数 */
  unlock() {
    this.strikes = 0;
    this.locked = false;
    this._persist();
  }
}

module.exports = { classify, ScopeGuard, MAX_STRIKES, RULES };
