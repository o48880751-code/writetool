/**
 * 随机取一句。
 *
 * @param {() => number} [rand] 注入随机源，方便判据固定结果
 * @returns {{t:string,a:string,w:string}|null}
 */
function pickLine(rand = Math.random) {
  if (!LINES.length) return null;
  const r = Number(rand());
  const safe = Number.isFinite(r) ? Math.min(Math.max(r, 0), 0.999999) : 0;
  return LINES[Math.floor(safe * LINES.length)];
}

